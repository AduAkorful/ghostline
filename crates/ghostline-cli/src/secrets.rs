use std::{
    fs,
    io::{self, Read},
    path::Path,
};

use serde::Deserialize;
use tari_crypto::ristretto::RistrettoSecretKey;

use crate::seal;

pub const PAYER_SECRET_ENV: &str = "GHOSTLINE_PAYER_SECRET";
/// Claim key for `unblind`. Wallet-built channel outputs are encrypted to the wallet view key, not the Ghostline payer key.
pub const CLAIM_SECRET_ENV: &str = "GHOSTLINE_CLAIM_SECRET";
pub const SEAL_SECRET_ENV: &str = "GHOSTLINE_SEAL_SECRET";
pub const INPUT_MASK_ENV: &str = "GHOSTLINE_INPUT_MASK";
pub const DEPOSIT_MASK_ENV: &str = "GHOSTLINE_DEPOSIT_MASK";
pub const FEE_SECRET_ENV: &str = "GHOSTLINE_FEE_SECRET";
pub const SESSION_ENV: &str = "GHOSTLINE_SESSION";
pub const VENDOR_ENV: &str = "GHOSTLINE_POLICY_VENDOR_HEX";
pub const UNSAFE_ENV: &str = "GHOSTLINE_POLICY_UNSAFE";

#[derive(Deserialize)]
struct KeyFile {
    format: String,
    role: String,
    secret_hex: String,
}

/// Load a key generated by `ghostline keygen --out`; the file must be private to its owner on Unix.
pub fn load_key_file(path: &Path, expected_role: &str) -> Result<RistrettoSecretKey, String> {
    let metadata = fs::metadata(path).map_err(|e| format!("key file: {e}"))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        if metadata.permissions().mode() & 0o077 != 0 {
            return Err("key file permissions must be owner-only (0600)".into());
        }
    }
    let bytes = fs::read(path).map_err(|e| format!("key file: {e}"))?;
    let key: KeyFile =
        serde_json::from_slice(&bytes).map_err(|_| "invalid key file".to_string())?;
    if key.format != "ghostline-key-v1" {
        return Err("unsupported key file format".into());
    }
    if key.role != expected_role {
        return Err(format!("key file role must be {expected_role}"));
    }
    seal::parse_secret("payer secret", &key.secret_hex)
}

/// Claim secret for unblinding: `--secret-hex`, then `GHOSTLINE_CLAIM_SECRET`, then `GHOSTLINE_PAYER_SECRET`.
pub fn load_claim_secret(flag: Option<&str>) -> Result<RistrettoSecretKey, String> {
    if flag.is_some() {
        return load_secret(flag, CLAIM_SECRET_ENV, "claim secret");
    }
    match std::env::var(CLAIM_SECRET_ENV) {
        Ok(v) if !v.trim().is_empty() => seal::parse_secret("claim secret", v.trim()),
        _ => load_secret(None, PAYER_SECRET_ENV, "claim secret"),
    }
}

/// CLI `--secret-hex` / env / stdin (`-`). Prints a warning when the value came from argv.
pub fn load_secret(
    flag: Option<&str>,
    env_name: &str,
    label: &str,
) -> Result<RistrettoSecretKey, String> {
    let hex = load_hex(flag, env_name, label)?;
    seal::parse_secret(label, &hex)
}

pub fn load_hex(flag: Option<&str>, env_name: &str, label: &str) -> Result<String, String> {
    if let Some(value) = flag {
        if value == "-" {
            let mut buf = String::new();
            io::stdin()
                .read_to_string(&mut buf)
                .map_err(|e| format!("{label} stdin: {e}"))?;
            let trimmed = buf.trim();
            if trimmed.is_empty() {
                return Err(format!("{label}: stdin was empty"));
            }
            return Ok(trimmed.to_string());
        }
        eprintln!(
            "warning: {label} passed on the command line; it will appear in process lists. Prefer {env_name} or --{label}=- with stdin."
        );
        return Ok(value.to_string());
    }
    match std::env::var(env_name) {
        Ok(v) if !v.trim().is_empty() => Ok(v.trim().to_string()),
        _ => Err(format!(
            "missing {label}: set {env_name}, pass --flag -, or (leaky) --flag <hex>"
        )),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use tari_utilities::ByteArray;

    fn temp_path() -> std::path::PathBuf {
        let stamp = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        std::env::temp_dir().join(format!(
            "ghostline-key-test-{}-{stamp}.json",
            std::process::id()
        ))
    }

    #[test]
    fn owner_only_payer_key_file_loads_and_role_is_checked() {
        let path = temp_path();
        let (secret, public) = tari_ootle_common_types::crypto::create_key_pair_from_seed(41);
        let json = serde_json::json!({
            "format": "ghostline-key-v1",
            "role": "payer",
            "secret_hex": ghostline_core::to_hex(secret.as_bytes()),
            "public_hex": ghostline_core::to_hex(public.as_bytes()),
        });
        ghostline_core::write_private_file(&path, json.to_string().as_bytes()).unwrap();

        assert!(load_key_file(&path, "payer").is_ok());
        assert!(load_key_file(&path, "service").is_err());
        std::fs::remove_file(path).unwrap();
    }

    #[cfg(unix)]
    #[test]
    fn key_file_with_group_or_world_permissions_is_rejected() {
        use std::os::unix::fs::PermissionsExt;

        let path = temp_path();
        let (secret, public) = tari_ootle_common_types::crypto::create_key_pair_from_seed(42);
        let json = serde_json::json!({
            "format": "ghostline-key-v1",
            "role": "payer",
            "secret_hex": ghostline_core::to_hex(secret.as_bytes()),
            "public_hex": ghostline_core::to_hex(public.as_bytes()),
        });
        ghostline_core::write_private_file(&path, json.to_string().as_bytes()).unwrap();
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o644)).unwrap();

        assert!(
            load_key_file(&path, "payer")
                .unwrap_err()
                .contains("owner-only")
        );
        std::fs::remove_file(path).unwrap();
    }
}
